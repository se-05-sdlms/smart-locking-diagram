ALL_KEY_MAP = {**CLASS_KEY_MAP, **SEQUENCE_KEY_MAP, **BLANK_KEY_MAP}
_KEY_PATTERN = re.compile(
    r'(?<![\w.])(' + '|'.join(
        re.escape(key) for key in sorted(ALL_KEY_MAP, key=len, reverse=True)
    ) + r')(?![\w.])'
)


def renumber_text(value: str) -> str:
    """Replace Report 4 references in one pass, without cascading."""
    return _KEY_PATTERN.sub(lambda match: ALL_KEY_MAP[match.group(1)], value)

